export type TKey = keyof (typeof dict)['en'];

const Ctx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: (k: TKey) => string }>({ 
  lang: 'ar',
  setLang: () => {},
  t: (k) => k as string,
});

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  // Arabic is the default language; site name stays "Open Send" in Latin.
  const [lang, setLangState] = useState<Lang>('ar');

  useEffect(() => {
    try {
      const saved = localStorage.getItem('opensend-lang') as Lang | null;
      const initial = saved === 'ar' || saved === 'en' ? saved : 'ar';
      setLangState(initial);
      document.documentElement.lang = initial;
      document.documentElement.dir = initial === 'ar' ? 'rtl' : 'ltr';
    } catch {}
  }, []);

  const setLang = (l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem('opensend-lang', l);
    } catch {}
    document.documentElement.lang = l;
    document.documentElement.dir = l === 'ar' ? 'rtl' : 'ltr';
  };

  const t = (k: TKey): string => {
    const table = dict[lang] as Record<string, string>;
    return table[k] ?? (dict.en as Record<string, string>)[k] ?? k;
  };

  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>;
}

export function useT(): { lang: Lang; setLang: (l: Lang) => void; t: (k: TKey) => string } {
  return useContext(Ctx);
}

export function LanguageSwitcher(): React.JSX.Element {
  const { lang, setLang } = useT();
  return (
    <div className="lang-switch" role="group" aria-label="Language">
      <button type="button" className={lang === 'en' ? 'active' : ''} onClick={() => setLang('en')}>
        English
      </button>
      <button type="button" className={lang === 'ar' ? 'active' : ''} onClick={() => setLang('ar')}>
        العربية
      </button>
    </div>
  );
}
